import pytest

from parser.core.postprocess import remove_academic_titles


@pytest.mark.parametrize(
    ("raw", "expected"),
    [
        ("Иванов И.И.", "Иванов И.И."),
        ("Петров-Водкин К.С.", "Петров-Водкин К.С."),
        ("доц. Зорин А.А.", "Зорин А.А."),
        ("ст. преп. Карсукова Н.К.", "Карсукова Н.К."),
        ("Иванов И.И. 22ч", "Иванов И.И."),
        ("Липкина Н. Г", "Липкина Н.Г."),
        ("доц. Зорин А.А., преп. Карсукова Н.К.", "Зорин А.А., Карсукова Н.К."),
        ("Иванов И.И., Иванов И.И.", "Иванов И.И."),
        ("Лекцию читает доц. Зорин А.А.", "Зорин А.А."),
        ("Лекция по математике", ""),
        ("", ""),
    ],
)
def test_remove_academic_titles(raw, expected):
    assert remove_academic_titles(raw) == expected
